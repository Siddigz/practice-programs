
def createMatrix():
    """
    Function Description:
        The purpose of this function is to create the matrices defined by the user and ensure
        no errors happen and it is safe to proceed
    Parameters:
        None
    Return:
        matrix (list): a list of lists that has numbers generated by the user 
    """

    #ensuring no problematic inputs pass through such as letters
    while True:
        try:
            rows = int(input("How many rows? "))
            columns = int(input("How many columns? "))
            break
        except ValueError:
            print("Try again, but with integers!")


    #creation of the matrix
    matrix = []




    for x in range(rows):
        while True:
            try:
                #list of digits for the "x" row
                row = input(f"Input the values for row {x} and seperate them using a comma. ").split(",")

                index = 0
                #making every string number into an integer number
                for number in row:
                    number = int(number)
                    row[index] = number
                    index += 1
                # if the digits match the required number, we break out of the loop
                if len(row) == columns:
                    break
                
                print("Try again, your values have to match your number of values in a column")
            except:
                print("Try again, use only integers")
        #successful creation of all the numbers and thus we append them to the row
        matrix.append(row)
    
    return matrix

def multipleMatrix(matA,matB):
    """
    Function Description:
        find the product of the parameters using nested for loops
    Parameters:
        matA (list): first matrix you want to multiply
        matB (list): second matrix you want to multiply
    Return:
        matC (list): product of matA and matB 
    """
    #making sure if it is even possible to multiply the 2 matrices
    if len(matA[0]) == len(matB):
        #keyNumber is the secret number that is the solution to solve the problem
        #it is the shared length between the 2 matrices so you can take the number from either matrix
        #keyNumber = len(matB)
        keyNumber = len(matA[0])
    else:
        return None

    #creation of the final matrix with the number of rows as we already know whats the dimenions of the product
    matC = []
    for rows in range(len(matA)):
        matC.append([])

    #the heart of the code: 
    for x in range(len(matA)):
        for y in range(len(matB[0])):
            product = 0
            #key number skillfully used to add the correct values to each other
            for key in range(keyNumber):
                product += matA[x][key] * matB[key][y]
            matC[x].append(product)

    return matC





def main():
    
    while True:
        print("Input Matrix A")
